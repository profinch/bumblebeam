#!/usr/bin/env python3
# makes vectors.h for test_host.c: addresses encoded by reference code (BIP173/350 bech32, base58check) and coinbases
import hashlib, os
CS = "qpzry9x8gf2tvdw0s3jn54khce6mua7l"
def polymod(v):
    G = [0x3b6a57b2, 0x26508e6d, 0x1ea119fa, 0x3d4233dd, 0x2a1462b3]; c = 1
    for x in v:
        b = c >> 25; c = (c & 0x1ffffff) << 5 ^ x
        for i in range(5): c ^= G[i] if (b >> i) & 1 else 0
    return c
def hrpx(h): return [ord(x) >> 5 for x in h] + [0] + [ord(x) & 31 for x in h]
def conv(d, f, t):
    acc = bits = 0; out = []
    for x in d:
        acc = acc << f | x; bits += f
        while bits >= t: bits -= t; out.append(acc >> bits & ((1 << t) - 1))
    if bits: out.append(acc << (t - bits) & ((1 << t) - 1))
    return out
def seg(hrp, ver, prog):
    d = [ver] + conv(prog, 8, 5); k = 1 if ver == 0 else 0x2bc830a3
    pm = polymod(hrpx(hrp) + d + [0] * 6) ^ k
    return hrp + '1' + ''.join(CS[x] for x in d + [pm >> 5 * (5 - i) & 31 for i in range(6)])
A = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"
def b58(ver, h):
    p = bytes([ver]) + h; p += hashlib.sha256(hashlib.sha256(p).digest()).digest()[:4]
    n = int.from_bytes(p, 'big'); s = ''
    while n: n, r = divmod(n, 58); s = A[r] + s
    return '1' * (len(p) - len(p.lstrip(b'\0'))) + s
h20, h32 = bytes(range(1, 21)), bytes(range(100, 132))
good = [  # address, script hex
    (seg('bc', 0, h20), '0014' + h20.hex()), (seg('bc', 0, h32), '0020' + h32.hex()), (seg('bc', 1, h32), '5120' + h32.hex()),
    (seg('tb', 0, h20), '0014' + h20.hex()), (seg('bc', 0, h20).upper(), '0014' + h20.hex()),
    (b58(0, h20), '76a914' + h20.hex() + '88ac'), (b58(5, h20), 'a914' + h20.hex() + '87'), (b58(0x6f, h20), '76a914' + h20.hex() + '88ac'),
    ('bc1qw508d6qejxtdg4y5r3zarvary0c5xw7kv8f3t4', None),
]
def flip(a, i): c = a[i]; alt = '1' if c != '1' else '2'; return a[:i] + (CS[(CS.index(c.lower()) + 1) % 32] if c.lower() in CS else alt) + a[i + 1:]
bad = [flip(seg('bc', 0, h20), 10), flip(seg('bc', 1, h32), -1), seg('bc', 0, h20)[:-1], seg('bc', 0, h20)[:6] + seg('bc', 0, h20)[6:].upper(),
       seg('bc', 1, h32)[:4] + 'q' + seg('bc', 1, h32)[5:], b58(0, h20)[:-1] + ('2' if b58(0, h20)[-1] != '2' else '3'), b58(0x30, h20),
       'bc1' + 'q' * 39, '', 'hello', seg('bc', 0, h20) + '.worker']
# a bech32 (v0 checksum) on a v1 program must fail: bech32m is required from v1
d = [1] + conv(h32, 8, 5); pm = polymod(hrpx('bc') + d + [0] * 6) ^ 1
bad.append('bc1' + ''.join(CS[x] for x in d + [pm >> 5 * (5 - i) & 31 for i in range(6)]))
def vi(n): return bytes([n]) if n < 0xfd else b'\xfd' + n.to_bytes(2, 'little')
def tx(outs):
    t = (1).to_bytes(4, 'little') + vi(1) + b'\0' * 32 + b'\xff' * 4 + vi(8) + b'\x03abc\0\0\0\0' + b'\xff' * 4 + vi(len(outs))
    for v, s in outs: t += v.to_bytes(8, 'little') + vi(len(s)) + s
    return t + b'\0' * 4
spk = bytes.fromhex('0014' + h20.hex()); other = bytes.fromhex('0014' + bytes(20).hex()); opret = bytes.fromhex('6a24aa21a9ed') + bytes(32)
cbs = [(tx([(312500000, spk), (0, opret)]), 100), (tx([(3125000, spk), (309375000, other)]), 1), (tx([(312500000, other), (0, spk[:5] + spk[5:])])[:-4], 0),
       (tx([(312500000, spk)])[:60], -1)]
with open(os.path.join(os.path.dirname(__file__), 'vectors.h'), 'w') as f:
    f.write('// generated by vectors.py\nstatic const struct { const char *a, *script; } GOOD[] = {\n')
    for a, s in good: f.write(f'    {{ "{a}", {chr(34) + s + chr(34) if s else "NULL"} }},\n')
    f.write('};\nstatic const char *const BAD[] = {\n' + ''.join(f'    "{a}",\n' for a in bad) + '};\n')
    f.write('static const struct { const char *tx; int pct; } CB[] = {\n' + ''.join(f'    {{ "{t.hex()}", {p} }},\n' for t, p in cbs) + '};\n')
    f.write(f'static const char SPK[] = "{spk.hex()}";\n')
