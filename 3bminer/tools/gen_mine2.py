#!/usr/bin/env python3
# generates main/mine2.S from main/mine.S: kernel variants hwmine_kK with START of block 1 after K words
# (the rest land while the engine streams W[0..K-1]) and the hit test of nonce N-1 done inside the engine wait of nonce N
import os
os.chdir(os.path.join(os.path.dirname(__file__), '..'))
src = open('main/mine.S').read()
loop_start = src.index('.Lloop:'); body = src[loop_start:]
blk2 = body[body.index('    // ---- block 2'):body.index('    loopnez a13, .Ld1')]
mid = body[body.index('    loopnez a13, .Ld1'):body.index('.Ld5:') + len('.Ld5:\n')]
prime = src[src.index('    // prime block1 words 8..15'):loop_start]
def kern(K):
    n = f'hwmine_k{K}'; L = lambda s: s.replace('.Ld', f'.Lk{K}d')
    regs = ['a13', 'a14', 'a15']; out = []
    if K: out.append(f'    l32i {regs[0]}, a2, 0')
    for i in range(K):
        if i + 1 < K: out.append(f'    l32i {regs[(i+1)%3]}, a2, {4*(i+1)}')
        out.append(f'    s32i {regs[i%3]}, a7, {4*i}')
    treg = ['a13', 'a14', 'a15', 'a11']; tail = list(range(K, 8))
    for j, i in enumerate(tail): out.append(f'    l32i {treg[j]}, a2, {4*i}')
    out.append('    s32i a12, a7, 0x90              // START (block 1)')
    for j, i in enumerate(tail): out.append(f'    s32i {treg[j]}, a7, {4*i}')
    b1 = '\n'.join(out) + '\n'
    chk = f'    and  a11, a6, a5                // nonce N-1: digest word 7 & mask, inside the engine wait\n    beqz a11, .Lk{K}prev\n'
    return f'''
    .align 4
    .global {n}
    .type {n}, @function
{n}:
    entry   a1, 32
    movi    a7, 0x3ff03000
    movi    a8, 0
    l32i    a9, a2, 76
    l32i    a10, a2, 80
    movi    a12, 1
    add     a4, a4, a3
    l32i    a5, a2, 92              // hit mask
    movi    a6, -1                  // no previous digest yet
{prime}.Lk{K}loop:
{b1}{blk2}{chk}{L(mid)}    l32i a6, a7, 28                 // digest word 7, tested in the next iteration
    addi a3, a3, 1
    bne  a3, a4, .Lk{K}loop
    and  a11, a6, a5
    beqz a11, .Lk{K}prev
    mov  a2, a3
    retw
.Lk{K}prev:                          // the hit belongs to nonce a3-1
    movi a14, 1
    s32i a14, a2, 96
    addi a2, a3, -1
    retw
    .size {n}, .-{n}
'''
open('main/mine2.S', 'w').write('// generated by tools/gen_mine2.py from mine.S - do not edit\n    .section .iram1, "ax"\n' + ''.join(kern(k) for k in (8, 7, 6, 5, 4)))
