#!/usr/bin/env python3
"""Deliver ui/ into a site. Stdlib only; run from anywhere.

  ui/build.py copy DEST_DIR          copy the library into DEST_DIR/ui/ (tokens/base/components .css,
                                     ui.css = the three in one, components/bb.js, charts/charts.js,
                                     VERSION = the commit it came from). For sites served as files:
                                     pool, explorer (Dockerfile), thermo (install.sh), NiceHash dash.
  ui/build.py inline IN.html OUT.html
                                     replace every <link rel="stylesheet" href=".../ui/NAME.css"> and
                                     <script src=".../ui/....js"></script> in IN with the file's text.
                                     For one-file pages: the 3BMiner firmware page, the extension popup.
  ui/build.py swift OUT.swift        the colour tokens as a Swift enum (the Mac miner's Theme).

A page refers to the library as ui/tokens.css, ui/base.css, ui/components.css (or ui/ui.css alone),
ui/components/bb.js, ui/charts/charts.js, relative to itself.
"""
import os
import re
import subprocess
import sys

UI = os.path.dirname(os.path.abspath(__file__))
CSS = ["tokens.css", "base.css", "components.css"]
JS = ["components/bb.js", "charts/charts.js"]


def read(rel):
    with open(os.path.join(UI, rel), encoding="utf-8") as f:
        return f.read()


def version():
    try:
        out = subprocess.run(["git", "-C", UI, "log", "-1", "--format=%h %cs", "--", "."], capture_output=True, text=True, check=True)
        dirty = subprocess.run(["git", "-C", UI, "status", "--porcelain", "--", "."], capture_output=True, text=True).stdout.strip()
        return out.stdout.strip() + (" +local changes" if dirty else "")
    except Exception:
        return "unknown"


def bundle_css():
    return "\n".join(f"/* ---- ui/{name} ---- */\n{read(name)}" for name in CSS)


def copy(dest):
    out = os.path.join(dest, "ui")
    for rel in CSS + JS:
        path = os.path.join(out, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(read(rel))
    with open(os.path.join(out, "ui.css"), "w", encoding="utf-8") as f:
        f.write(bundle_css())
    with open(os.path.join(out, "VERSION"), "w", encoding="utf-8") as f:
        f.write(version() + "\n")
    print(f"ui -> {out} ({version()})")


def inline(src, dst):
    with open(src, encoding="utf-8") as f:
        html = f.read()
    n = 0

    def css(m):
        nonlocal n
        name = m.group(1)
        text = bundle_css() if name == "ui.css" else read(name)
        n += 1
        return f"<style>/* ui/{name} {version()} */\n{text}</style>"

    def js(m):
        nonlocal n
        n += 1
        return f"<script>/* ui/{m.group(1)} {version()} */\n{read(m.group(1))}</script>"

    html = re.sub(r'<link\s+rel="stylesheet"\s+href="(?:[^"]*/)?ui/((?:tokens|base|components|ui)\.css)"\s*/?>', css, html)
    html = re.sub(r'<script\s+src="(?:[^"]*/)?ui/((?:components|charts)/[\w-]+\.js)"\s*>\s*</script>', js, html)
    with open(dst, "w", encoding="utf-8") as f:
        f.write(html)
    print(f"{src} -> {dst}: {n} ui files inlined ({version()})")


def swift(dst):
    tokens = read("tokens.css")
    root = tokens.split(":root[data-chain")[0]
    lines = [
        "// Generated by ui/build.py swift from ui/tokens.css - do not edit; change the tokens and regenerate.",
        "import SwiftUI",
        "",
        "enum BBTokens {",
    ]
    for name, hexv in re.findall(r"--([\w-]+):\s*#([0-9a-fA-F]{6})\b", root):
        ident = re.sub(r"-(\w)", lambda m: m.group(1).upper(), name)
        r, g, b = (int(hexv[i:i + 2], 16) / 255 for i in (0, 2, 4))
        lines.append(f"    static let {ident} = Color(red: {r:.4f}, green: {g:.4f}, blue: {b:.4f}) // #{hexv.lower()}")
    btc = re.search(r":root\[data-chain=\"bitcoin\"\][^{]*\{[^}]*--accent:\s*#([0-9a-fA-F]{6})", tokens)
    if btc:
        h = btc.group(1)
        r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
        lines.append(f"    static let accentBitcoin = Color(red: {r:.4f}, green: {g:.4f}, blue: {b:.4f}) // #{h.lower()}")
    lines.append("}")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"tokens -> {dst}")


def main(argv):
    if len(argv) == 3 and argv[1] == "copy":
        copy(argv[2])
    elif len(argv) == 4 and argv[1] == "inline":
        inline(argv[2], argv[3])
    elif len(argv) == 3 and argv[1] == "swift":
        swift(argv[2])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv)
