# Generates pool/web/404.svg: "4 [empty honeycomb cell] 4" with the logo's bee peeking into the cell.
import math, sys
R = 30                      # hexagon radius (pointy top, like the logo)
W = math.sqrt(3) * R        # horizontal distance between neighbours
CX, CY = 280, 122

def hexpath(cx, cy, r):
    pts = [(cx + r * math.cos(math.radians(-90 + 60 * k)), cy + r * math.sin(math.radians(-90 + 60 * k))) for k in range(6)]
    return 'M' + ' '.join(f'{x:.1f} {y:.1f}' for x, y in pts) + 'z'

# the ring around the empty cell, and a few faded cells further out for texture
# The two diagonal neighbours (top right, bottom left) are left out: the bees hover there.
# (dx, dy, honey)
ring = [(W, 0, True), (W / 2, 1.5 * R, True), (-W, 0, False), (-W / 2, -1.5 * R, True)]
outer = [(-1.5 * W, 1.5 * R), (0, 3 * R), (-1.5 * W, -1.5 * R), (1.5 * W, 1.5 * R), (1.5 * W, -1.5 * R), (0, -3 * R)]


def bee(x, y, angle, mirror, delay='0s'):
    """The logo's bee at (x, y), turned by angle; mirror = head to the left."""
    sx = -3.4 if mirror else 3.4
    return f'''<g transform="translate({x} {y}) rotate({angle}) scale({sx} 3.4) translate(-16 -17)">
<g class="bee" style="animation-delay:{delay}">
<g class="trail" stroke="#fff" stroke-width="1.3" stroke-linecap="round"><path class="t1" d="M4.5 20h3.5"/><path class="t2" d="M3.5 23.5h2.5"/></g>
<ellipse class="wing wl" cx="14.5" cy="10.8" rx="3.6" ry="2.1" transform="rotate(-24 14.5 10.8)" fill="#fff" fill-opacity=".9" stroke="#042548" stroke-width=".6"/>
<ellipse class="wing wr" cx="20" cy="10.8" rx="3.6" ry="2.1" transform="rotate(24 20 10.8)" fill="#fff" fill-opacity=".9" stroke="#042548" stroke-width=".6"/>
<rect x="9.5" y="13.5" width="15" height="9" rx="4.5" fill="#042548" stroke="#39fff2" stroke-opacity=".35" stroke-width=".5"/>
<g clip-path="url(#stripes)" fill="#f4ce4a"><rect x="13.3" y="13" width="3" height="10"/><rect x="18.6" y="13" width="3" height="10"/></g>
<circle class="eye" cx="22.6" cy="17" r=".95" fill="#39fff2"/>
</g>
</g>'''

cells = []
for i, (dx, dy, has_honey) in enumerate(ring):
    cls = 'honey' if has_honey else 'comb'
    cells.append(f'<path class="{cls}" style="animation-delay:{-i * 0.5:.1f}s" d="{hexpath(CX + dx, CY + dy, R - 2)}"/>')
for dx, dy in outer:
    cells.append(f'<path class="far" d="{hexpath(CX + dx, CY + dy, R - 2)}"/>')

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 560 250" role="img" aria-label="404: an empty honeycomb cell, and two bees looking into it">
<!-- BumbleBeam 404: generated by brand/src/gen404.py -->
<defs>
<linearGradient id="beam" x1="0" y1="1" x2="1" y2="0"><stop offset="0" stop-color="#0b76ff"/><stop offset="1" stop-color="#39fff2"/></linearGradient>
<radialGradient id="hole"><stop offset="0" stop-color="#010f1f"/><stop offset="1" stop-color="#03213c"/></radialGradient>
<clipPath id="stripes"><rect x="9.5" y="13.5" width="15" height="9" rx="4.5"/></clipPath>
</defs>
<style>
.four {{ font: 800 150px -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; fill: url(#beam); }}
.honey {{ fill: #f4ce4a; fill-opacity: .82; stroke: #c9a227; stroke-width: 1.5; animation: honey 4s ease-in-out infinite; }}
.comb {{ fill: rgba(255,255,255,.05); stroke: rgba(255,255,255,.22); stroke-width: 1.5; }}
.far {{ fill: none; stroke: rgba(255,255,255,.08); stroke-width: 1.5; }}
.empty {{ fill: url(#hole); stroke: #39fff2; stroke-width: 2; stroke-dasharray: 6 5; animation: empty 6s linear infinite; }}
.bee {{ animation: bob 3s ease-in-out infinite; }}
.wing {{ transform-box: fill-box; transform-origin: 50% 100%; animation: flutter .22s ease-in-out infinite alternate; }}
.wr {{ animation-delay: -.11s; }}
.trail path {{ animation: trail 1.5s ease-in-out infinite; }}
.trail .t2 {{ animation-delay: -.5s; }}
.eye {{ animation: blink 4s steps(1) infinite; }}
@keyframes honey {{ 0%, 100% {{ fill-opacity: .82; }} 50% {{ fill-opacity: .62; }} }}
@keyframes empty {{ to {{ stroke-dashoffset: -66; }} }}
@keyframes bob {{ 0%, 100% {{ transform: translate(0, 0); }} 50% {{ transform: translate(-3px, 4px); }} }}
@keyframes flutter {{ from {{ transform: rotate(-9deg) scaleY(.92); }} to {{ transform: rotate(9deg) scaleY(1.05); }} }}
@keyframes trail {{ 0%, 100% {{ stroke-opacity: .25; }} 50% {{ stroke-opacity: .85; }} }}
@keyframes blink {{ 0%, 93%, 100% {{ opacity: 1; }} 95%, 98% {{ opacity: 0; }} }}
@media (prefers-reduced-motion: reduce) {{ .honey, .empty, .bee, .wing, .trail path, .eye {{ animation: none; }} }}
</style>
<text class="four" x="120" y="176" text-anchor="middle">4</text>
<text class="four" x="440" y="176" text-anchor="middle">4</text>
{''.join(cells)}
<path class="empty" d="{hexpath(CX, CY, R - 2)}"/>
{bee(310, 60, -40, True)}
{bee(243, 178, -40, False, "-1.4s")}
</svg>
'''
# python3 brand/src/gen404.py pool/web/404.svg
open(sys.argv[1], "w").write(svg)
print(len(svg))
